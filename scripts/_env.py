#!/usr/bin/env python3
"""Writes ENVIRONMENT.md: the software versions the results were computed with (listed in the README under Dependencies).

Purpose : reproducibility record, generated, never edited by hand.
Input   : the installed Python and R
Output  : ENVIRONMENT.md next to this file
Usage   : python3 _env.py   (run_all.sh calls it last)
"""
import datetime, platform, subprocess, sys
from pathlib import Path

R_PKGS = ["glmnet", "gbm", "ranger", "grf", "Matrix"]

def main():
    r = subprocess.run(["Rscript", "-e", "cat(R.version.string, '\\n'); for (p in c(%s)) cat(p, as.character(packageVersion(p)), '\\n')"
                        % ", ".join(f'"{p}"' for p in R_PKGS)], capture_output=True, text=True)
    lines = [l for l in r.stdout.splitlines() if l.strip()]
    py = f"Python {platform.python_version()} ({sys.executable})"
    md = ["# Environment", "", f"*Generated by `_env.py` on {datetime.date.today().isoformat()}. Pipeline stages use only the Python standard library; R stages need the packages below.*", "",
          f"- {platform.system()} {platform.release()}, {platform.machine()}", f"- {py}", f"- {lines[0] if lines else 'R not found'}"]
    md += [f"- R package {l}" for l in lines[1:]]
    Path(__file__).with_name("ENVIRONMENT.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))

if __name__ == "__main__":
    main()
